

DROP TABLE IF EXISTS public.list_field_map;

CREATE TABLE public.list_field_map
	(
	  id          UUID NOT NULL DEFAULT gen_random_uuid()
	, field_id    VARCHAR (100) NOT NULL
	, seq         BIGINT GENERATED BY DEFAULT AS IDENTITY
	, list_id     UUID NOT NULL
	, value       VARCHAR (255) NOT NULL
	, is_hidden   BOOL NOT NULL DEFAULT false
	, sort_order  INTEGER NOT NULL DEFAULT 0
	, created_on  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
	, created_by  UUID
	, modified_on TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
	, modified_by UUID
	, is_default  BOOL NOT NULL DEFAULT false
	, CONSTRAINT list_field_map_pkey PRIMARY KEY (id)
	, CONSTRAINT list_field_map_list_id_fkey FOREIGN KEY (list_id) REFERENCES public.list_master (id) ON UPDATE NO ACTION ON DELETE NO ACTION
	)
	WITH (OIDS = FALSE);